/* Склонение названия региона в предложный падеж: «в Московской области».
 *
 * Названия приходят из базы в именительном («Московская область»), а в тексте
 * страницы нужен предложный. Подстановка без склонения — «в Московская область» —
 * на продающей странице читается как машинный перевод и убивает доверие раньше,
 * чем человек дойдёт до цены.
 *
 * Правил немного: у российских регионов всего несколько типов названий.
 */

const CITIES: Record<string, string> = {
  "Москва": "Москве",
  "Санкт-Петербург": "Санкт-Петербурге",
  "Севастополь": "Севастополе",
};

/** «Московская область» → «Московской области» */
export function regionIn(name: string): string {
  if (!name) return "";
  if (CITIES[name]) return CITIES[name];

  // Республика Татарстан → Республике Татарстан (собственное имя не трогаем)
  if (name.startsWith("Республика ")) {
    return name.replace("Республика ", "Республике ");
  }
  // Чувашская Республика → Чувашской Республике
  if (name.endsWith("Республика")) {
    return name.replace(/ая Республика$/, "ой Республике");
  }
  // Ханты-Мансийский автономный округ → Ханты-Мансийском автономном округе
  if (name.endsWith("автономный округ")) {
    return name.replace(/ий автономный округ$/, "ом автономном округе")
               .replace(/ый автономный округ$/, "ом автономном округе");
  }
  // Еврейская автономная область → Еврейской автономной области
  if (name.endsWith("автономная область")) {
    return name.replace(/ая автономная область$/, "ой автономной области");
  }
  if (name.endsWith("область")) {
    return name.replace(/ая область$/, "ой области");
  }
  if (name.endsWith("край")) {
    return name.replace(/ий край$/, "ом крае").replace(/ой край$/, "ом крае");
  }

  // Незнакомый тип названия — оборачиваем так, чтобы падеж не требовался
  return `регионе «${name}»`;
}
